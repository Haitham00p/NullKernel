#!/usr/bin/env bash
# genvault.sh — build the ncc header + symbol vault.
# Usage: genvault.sh <kernel.elf> <out.c> [out.h]
#   - packs every *.h from the source tree into a header table (auto:
#     adding a new .h anywhere picks it up on the next build)
#   - packs the global symbol table of <kernel.elf> into a symbol table so
#     ncc can link user programs against kernel functions by name
set -euo pipefail

KERNEL="${1:?usage: $0 <kernel.elf> <out.c> [out.h]}"
OUT_C="${2:?usage: $0 <kernel.elf> <out.c> [out.h]}"
OUT_H="${3:-${OUT_C%.c}.h}"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

HEADER_DIRS="libc include source arch drivers fs kernel lib mm shell"

escape_c() {
    sed -e ':a;N;$!ba' \
        -e 's/\\/\\\\/g' \
        -e 's/"/\\"/g' \
        -e 's/\r//g' \
        -e 's/\t/\\t/g' \
        -e 's/\x01/\\x01/g' \
        -e 's/\x02/\\x02/g' \
        -e 's/\x03/\\x03/g' \
        -e 's/\x04/\\x04/g' \
        -e 's/\x05/\\x05/g' \
        -e 's/\x06/\\x06/g' \
        -e 's/\x07/\\x07/g' \
        -e 's/\x08/\\x08/g' \
        -e 's/\x0b/\\x0b/g' \
        -e 's/\x0c/\\x0c/g' \
        -e 's/\x0e/\\x0e/g' \
        -e 's/\x0f/\\x0f/g' \
        -e 's/\x10/\\x10/g' \
        -e 's/\x11/\\x11/g' \
        -e 's/\x12/\\x12/g' \
        -e 's/\x13/\\x13/g' \
        -e 's/\x14/\\x14/g' \
        -e 's/\x15/\\x15/g' \
        -e 's/\x16/\\x16/g' \
        -e 's/\x17/\\x17/g' \
        -e 's/\x18/\\x18/g' \
        -e 's/\x19/\\x19/g' \
        -e 's/\x1a/\\x1a/g' \
        -e 's/\x1b/\\x1b/g' \
        -e 's/\x1c/\\x1c/g' \
        -e 's/\x1d/\\x1d/g' \
        -e 's/\x1e/\\x1e/g' \
        -e 's/\x1f/\\x1f/g' \
        -e 's/\n/\\n/g'
}

HDR_FILES=""
for DIR in $HEADER_DIRS; do
    for FILE in $(find "$ROOT/$DIR" -name '*.h' -type f 2>/dev/null | sort); do
        HDR_FILES="$HDR_FILES $FILE"
    done
done

{
    printf '/* generated by ncc/genvault.sh — do not edit */\n'
    printf '#include "ncc/vault_gen.h"\n\n'

    printf 'static const char *const NccHeaderContents[] =\n{\n'
    COUNT=0
    for FILE in $HDR_FILES; do
        ESC="$(escape_c < "$FILE")"
        if [ "$COUNT" -gt 0 ]; then printf ',\n'; fi
        printf '    "%s"' "$ESC"
        COUNT=$((COUNT + 1))
    done
    printf '\n};\n\n'

    printf 'const NccHeaderVault NccHeaders[] = {\n'
    IDX=0
    for FILE in $HDR_FILES; do
        REL="${FILE#$ROOT/}"
        NAME="$(basename "$FILE")"
        printf '    { "%s", "%s", NccHeaderContents[%d] },\n' "$NAME" "$REL" "$IDX"
        IDX=$((IDX + 1))
    done
    printf '};\n'
HDR_COUNT="$COUNT"
printf 'const uint32_t NccHeaderCount = %d;\n' "$HDR_COUNT"
printf '\n'

printf 'const NccSymbolVault NccSymbols[] = {\n'
COUNT=0
while read -r ADDR TYPE NAME; do
    printf '    { "%s", 0x%sULL },\n' "$NAME" "$ADDR"
    COUNT=$((COUNT + 1))
done < <(nm -g --defined-only "$KERNEL" 2>/dev/null |
    awk '{ if ($2 == "T" || $2 == "D" || $2 == "B" || $2 == "R") print $1, $2, $3 }' |
    grep -v ' [TDBR] Ncc[A-Za-z]' || true)
printf '};\n'
printf 'const uint32_t NccSymbolCount = %d;\n' "$COUNT"
} > "$OUT_C"

{
    printf '#ifndef NCC_VAULT_GEN_H\n'
    printf '#define NCC_VAULT_GEN_H\n\n'
    printf '#include <stdint.h>\n\n'
    printf 'typedef struct\n{\n    const char *Name;\n    const char *Path;\n    const char *Content;\n} NccHeaderVault;\n\n'
    printf 'typedef struct\n{\n    const char *Name;\n    uint64_t Addr;\n} NccSymbolVault;\n\n'
    printf 'extern const NccHeaderVault NccHeaders[];\n'
    printf 'extern const uint32_t NccHeaderCount;\n'
    printf 'extern const NccSymbolVault NccSymbols[];\n'
    printf 'extern const uint32_t NccSymbolCount;\n\n'
    printf '#endif\n'
} > "$OUT_H"

echo "ncc vault: $COUNT symbols, $HDR_COUNT headers -> $OUT_C"
